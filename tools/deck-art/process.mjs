#!/usr/bin/env node
/**
 * Turn the generated deck-art PNGs into the WebP sets the app ships, and write
 * apps/web/src/components/deckArt/art/MANIFEST.json — the provenance record
 * for every shipped file (prompt, tool, model, date, source hash, every
 * processing step, every output's real size in bytes).
 *
 *   node tools/deck-art/process.mjs [--raw <dir>]
 *
 * <raw> is generate.mjs's output (default `.deck-art-raw/`): <id>.png plus
 * generation.json. Only ids present there are processed; the manifest is
 * rewritten from what is on disk, so it cannot drift from the files.
 *
 * Processing, per layer:
 *   box       centre-crop to the box face's 88:120 aspect → grayscale →
 *             normalise levels (0.5–99.5th percentile) → resize to 104/208/312
 *             px wide (1x/2x/3x of a phone-width tile's face) → WebP q76/70/60
 *             (denser screens hide compression in smaller physical pixels)
 *   backdrop  centre-crop to the scene's 16:9 → grayscale → normalise levels →
 *             a light blur (it is a defocused studio, and noise costs bytes) →
 *             400 and 800 px wide (1x, 2x) → WebP q66/62. 3x screens use the 2x
 *             file: the backdrop is soft by design, and 1200 px would cost ~70%
 *             more bytes for detail it does not have.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { LIBRARY } from './library.mjs'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO = path.resolve(HERE, '..', '..')
const require = createRequire(path.join(REPO, 'package.json'))
const sharp = require('sharp')

const arg = (name, fallback) => {
  const i = process.argv.indexOf(name)
  return i > 0 ? process.argv[i + 1] : fallback
}
const RAW = path.resolve(arg('--raw', path.join(REPO, '.deck-art-raw')))
const OUT = path.join(REPO, 'apps', 'web', 'src', 'components', 'deckArt', 'art')
fs.mkdirSync(OUT, { recursive: true })

const generation = JSON.parse(fs.readFileSync(path.join(RAW, 'generation.json'), 'utf8'))

const BOX = { aspect: 88 / 120, widths: [104, 208, 312], quality: [76, 70, 60] }
const BACKDROP = { aspect: 16 / 9, widths: [400, 800], quality: [66, 62] }

async function processOne(item) {
  const src = path.join(RAW, `${item.id}.png`)
  if (!fs.existsSync(src)) return null
  const raw = fs.readFileSync(src)
  const meta = await sharp(raw).metadata()
  const spec = item.layer === 'box' ? BOX : BACKDROP
  // Centre crop to the target aspect.
  let cw = meta.width
  let ch = Math.round(cw / spec.aspect)
  if (ch > meta.height) {
    ch = meta.height
    cw = Math.round(ch * spec.aspect)
  }
  const left = Math.round((meta.width - cw) / 2)
  const top = Math.round((meta.height - ch) / 2)
  const steps = [
    `crop ${cw}x${ch} at ${left},${top} (centre, ${item.layer === 'box' ? '88:120' : '16:9'})`,
    'grayscale',
    'normalise levels 0.5–99.5th percentile',
  ]
  if (item.layer === 'backdrop') steps.push('gaussian blur sigma 0.8 (at 2x)')
  const outputs = []
  for (const [i, w] of spec.widths.entries()) {
    const h = Math.round(w / spec.aspect)
    let img = sharp(raw).extract({ left, top, width: cw, height: ch }).grayscale().normalise({ lower: 0.5, upper: 99.5 })
    img = img.resize(w, h, { kernel: 'lanczos3' })
    if (item.layer === 'backdrop') img = img.blur(i === 0 ? 0.4 : 0.8)
    const file = `${item.id}@${i + 1}x.webp`
    const buf = await img.webp({ quality: spec.quality[i], effort: 6, smartSubsample: true }).toBuffer()
    fs.writeFileSync(path.join(OUT, file), buf)
    outputs.push({ file, density: `${i + 1}x`, width: w, height: h, bytes: buf.length })
  }
  steps.push(`resize (lanczos3) to ${spec.widths.join('/')} px wide`, `WebP q${spec.quality.join('/')} (per density), effort 6`)
  const g = generation[item.id] ?? {}
  return {
    id: item.id,
    layer: item.layer,
    family: item.family,
    variant: item.variant,
    subject: item.subject,
    prompt: item.prompt,
    tool: g.tool ?? 'Codex CLI (codex exec)',
    model: g.model ?? null,
    imageTool: g.imageTool ?? null,
    generatedAt: g.generatedAt ?? null,
    source: { width: meta.width, height: meta.height, sha256: crypto.createHash('sha256').update(raw).digest('hex') },
    processing: steps,
    outputs,
  }
}

const assets = []
for (const item of LIBRARY) {
  const a = await processOne(item)
  if (a) assets.push(a)
}
const total = (layer, density) =>
  assets.filter((a) => a.layer === layer).reduce((n, a) => n + (a.outputs.find((o) => o.density === density)?.bytes ?? 0), 0)
const manifest = {
  $comment:
    'Generated by tools/deck-art/process.mjs from tools/deck-art/library.mjs and the Codex generation record. Do not hand-edit: byte counts and sizes are read from the files on disk.',
  generatedAt: new Date().toISOString(),
  license:
    'Original images generated for DeckPal with the Codex CLI image tool under the maintainer’s account. Abstract and material subjects only: no text, logos, people, creatures or game characters (see each prompt).',
  totals: {
    assets: assets.length,
    bytes: assets.reduce((n, a) => n + a.outputs.reduce((m, o) => m + o.bytes, 0), 0),
    box1x: total('box', '1x'),
    box2x: total('box', '2x'),
    box3x: total('box', '3x'),
    backdrop1x: total('backdrop', '1x'),
    backdrop2x: total('backdrop', '2x'),
  },
  assets,
}
fs.writeFileSync(path.join(OUT, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n')
console.log(`${assets.length} assets, ${(manifest.totals.bytes / 1024).toFixed(0)} KiB total`, manifest.totals)
