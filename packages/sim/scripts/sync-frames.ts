/**
 * Fetch the printed frame of every Standard printing the frame snapshot does not have yet, from the public DeckPal
 * catalog (GET <api>/cards/:id, the same source and the same fields as scripts/fetch-frames.mjs), and add them to
 * src/cards/frames-extra/std-new.ts (registered in frames-extra/index.ts on first use).
 *
 * "Standard" means the regulation marks in apps/api/src/deck/data/formats.json (standard.legal_marks), read at run
 * time; the printing list comes from GET <api>/search?set=<id> over every Scarlet & Violet / Mega Evolution era set.
 *
 *   node --import tsx scripts/sync-frames.ts --dry-run        # list what is missing, fetch nothing
 *   node --import tsx scripts/sync-frames.ts                  # fetch and write the missing frames
 *   node --import tsx scripts/sync-frames.ts --limit 200      # at most 200 this run (resume by running again)
 *   node --import tsx scripts/sync-frames.ts --set sv11       # only this set's printings
 *   node --import tsx scripts/sync-frames.ts --out <file>     # write to a scratch file instead (not registered)
 *
 * Read-only GETs, one at a time with a pause (SIM_FETCH_DELAY_MS, default 150). It never edits an existing frame:
 * a printing already in the snapshot is skipped (use scripts/fetch-frames.mjs <ids> to refresh specific frames).
 * Run it BEFORE refresh-card-tables.ts has changed anything and again after, since printed Weakness/Resistance
 * change a printing's text key (see CARDS.md, "New set, rotation, FAQ update").
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { FRAMES } from '../src/cards/frames-all.js';
import { API, catalogPrintings, catalogSets, standardMarks } from './lib/catalog.js';
import { getJson } from './lib/net.js';

const argv = process.argv.slice(2);
const DRY = argv.includes('--dry-run');
const flag = (name: string) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
const LIMIT = Number(flag('--limit') ?? Infinity);
const ONLY_SET = flag('--set');

const OUT_ARG = flag('--out'); // a scratch file instead of std-new.ts (not registered; for measuring)
const OUT = OUT_ARG ? pathToFileURL(resolve(OUT_ARG)) : new URL('../src/cards/frames-extra/std-new.ts', import.meta.url);
const INDEX = new URL('../src/cards/frames-extra/index.ts', import.meta.url);
const KEEP = ['cardId', 'name', 'category', 'hp', 'stage', 'suffix', 'evolvesFrom', 'trainerType', 'energyType', 'retreat', 'types', 'effect', 'regulationMark', 'attacks', 'abilities', 'weaknesses', 'resistances'];
const HEAD = [
  '// GENERATED by scripts/sync-frames.ts from the DeckPal catalog (GET /api/cards/:id): Standard printings added after the first',
  '// snapshot, one entry per printing. Do not edit by hand.',
  "import type { CardFrame } from '../../types.js';",
  '',
  'export const FRAMES: Record<string, CardFrame> = ',
].join('\n');

const marks = standardMarks();
const sets = (await catalogSets()).filter((s) => !ONLY_SET || s.setId === ONLY_SET);
const standard = (await catalogPrintings(sets)).filter((p) => p.mark && marks.includes(p.mark));
const missing = standard.filter((p) => !FRAMES[p.cardId]).map((p) => p.cardId).sort();
console.log(`Standard marks ${marks.join('/')}: ${standard.length} Standard printings in the catalog, ${standard.length - missing.length} in the snapshot, ${missing.length} missing`);
const bySet = new Map<string, number>();
for (const id of missing) bySet.set(id.slice(0, id.lastIndexOf('-')), (bySet.get(id.slice(0, id.lastIndexOf('-'))) ?? 0) + 1);
console.log([...bySet].map(([s, n]) => `${s}:${n}`).join(' '));
if (DRY || !missing.length) process.exit(0);

const marker = 'CardFrame> = ';
const src = existsSync(OUT) ? readFileSync(OUT, 'utf8') : `${marker}{};`;
const frames = JSON.parse(src.slice(src.indexOf(marker) + marker.length).replace(/;\s*$/, '')) as Record<string, unknown>;
let fetched = 0;
const failed: string[] = [];
for (const id of missing.slice(0, LIMIT)) {
  try {
    const { card } = await getJson<{ card: Record<string, unknown> }>(`${API}/cards/${encodeURIComponent(id)}`);
    frames[id] = Object.fromEntries(KEEP.map((k) => [k, card[k] ?? null]));
    fetched++;
  } catch (e) {
    failed.push(`${id}: ${(e as Error).message}`);
  }
  if (fetched % 100 === 0 && fetched) console.log(`  ${fetched} fetched`);
}
const sorted = Object.fromEntries(Object.keys(frames).sort().map((k) => [k, frames[k]]));
writeFileSync(OUT, `${HEAD}${JSON.stringify(sorted, null, 1)};\n`);

// Register the file once in frames-extra/index.ts.
let index = readFileSync(INDEX, 'utf8');
if (!OUT_ARG && !index.includes("'./std-new.js'")) {
  const eol = index.includes('\r\n') ? '\r\n' : '\n';
  index = index.replace(/(import \{ FRAMES as [A-Z_]+ \} from '[^']+';)(?![\s\S]*import \{ FRAMES as)/, `$1${eol}import { FRAMES as STD_NEW } from './std-new.js';`);
  index = index.replace(/(\s+\.\.\.[A-Z_]+,)(\s*\};)/, `$1${eol}  ...STD_NEW,$2`);
  writeFileSync(INDEX, index);
  console.log('registered std-new.ts in frames-extra/index.ts');
}
console.log(`frames: ${fetched} fetched, ${Object.keys(sorted).length} in std-new.ts${failed.length ? `, ${failed.length} FAILED:\n  ${failed.join('\n  ')}` : ''}`);
if (failed.length) process.exitCode = 1;
