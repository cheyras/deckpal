import { listTools, type AdvertisedTool } from './surface.js';

/**
 * apps/mcp/TOOLS.md, generated from what `tools/list` actually advertises.
 *
 * Hand-written tool lists drifted: on 2026-10-12 the repo claimed 23, 26, 27
 * and 28 tools in different places, and DEPLOYMENT.md's list was missing
 * `battle_digest`. This renders the list from the server itself — names,
 * titles, read/write, the annotations a client is shown, every argument with
 * its type and default, and the description the model reads — so the doc
 * cannot disagree with the code. `pnpm mcp:tools-doc` rewrites the file, and
 * apps/mcp/src/__tests__/docs.test.ts fails when the committed copy is stale.
 */

export interface ToolCounts {
  /** Tools every full connection is shown. */
  tools: number;
  read: number;
  write: number;
  /** Shown only to a token holding the Deck-E improvement capability. */
  gated: number;
}

export async function toolCounts(): Promise<ToolCounts> {
  const full = (await listTools()).tools;
  const withGated = (await listTools({ deckeImprovementRead: true })).tools;
  const read = full.filter((t) => t.annotations?.readOnlyHint === true).length;
  return { tools: full.length, read, write: full.length - read, gated: withGated.length - full.length };
}

/** Text made safe for one markdown table cell: backslashes first, then pipes, then line breaks. */
const cell = (s: string): string => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

function typeOf(p: Record<string, unknown>): string {
  if (Array.isArray(p.enum)) return (p.enum as unknown[]).map((v) => JSON.stringify(v)).join(' | ');
  if (Array.isArray(p.anyOf)) return (p.anyOf as Record<string, unknown>[]).map(typeOf).join(' or ');
  if (p.type === 'array') {
    const items = (p.items ?? {}) as Record<string, unknown>;
    return `${items.type === 'object' ? 'object' : typeOf(items)}[]`;
  }
  return String(p.type ?? 'any');
}

function hints(t: AdvertisedTool): string {
  const a = t.annotations ?? {};
  if (a.readOnlyHint) return 'read';
  return ['write', a.destructiveHint ? 'destructive' : 'additive', a.idempotentHint ? 'idempotent' : null].filter(Boolean).join(', ');
}

function section(t: AdvertisedTool, gated: boolean): string[] {
  const props = Object.entries(t.inputSchema?.properties ?? {});
  const required = new Set(t.inputSchema?.required ?? []);
  const lines = [
    `<a id="${t.name}"></a>`,
    '',
    `### \`${t.name}\` — ${t.title ?? t.name}`,
    '',
    `${hints(t)}${gated ? ' · capability-gated' : ''} · annotations \`${JSON.stringify(t.annotations ?? {})}\``,
    '',
    (t.description ?? '').trim(),
    '',
  ];
  if (props.length === 0) {
    lines.push('No arguments.', '');
    return lines;
  }
  lines.push('| argument | type | required | default | description |', '|---|---|---|---|---|');
  for (const [name, p] of props) {
    const dflt = p.default === undefined ? '' : `\`${JSON.stringify(p.default)}\``;
    lines.push(`| \`${name}\` | ${cell(typeOf(p))} | ${required.has(name) ? 'yes' : ''} | ${dflt} | ${cell(String(p.description ?? ''))} |`);
  }
  lines.push('');
  return lines;
}

/** The markers around the generated tool list in apps/mcp/README.md. */
export const README_BEGIN = '<!-- tools:begin — generated by `pnpm mcp:tools-doc`; edit the registry, not this list -->';
export const README_END = '<!-- tools:end -->';

/** The README's tool list: names by kind, read from tools/list. */
export async function renderReadmeTools(): Promise<string> {
  const full = (await listTools()).tools;
  const names = new Set(full.map((t) => t.name));
  const gated = (await listTools({ deckeImprovementRead: true })).tools.filter((t) => !names.has(t.name));
  const link = (t: AdvertisedTool) => `[\`${t.name}\`](TOOLS.md#${t.name})`;
  const reads = full.filter((t) => t.annotations?.readOnlyHint);
  const writes = full.filter((t) => !t.annotations?.readOnlyHint);
  return [
    README_BEGIN,
    '',
    `**Read (${reads.length}):** ${reads.map(link).join(', ')}.`,
    '',
    `**Write (${writes.length}):** ${writes.map(link).join(', ')}.`,
    '',
    `**Capability-gated reads (${gated.length}):** ${gated.map(link).join(', ')} — only for a token holding the Deck-E improvement capability.`,
    '',
    README_END,
  ].join('\n');
}

/** `readme` with its generated region replaced by `region`. */
export function fillReadme(readme: string, region: string): string {
  const begin = readme.indexOf(README_BEGIN);
  const end = readme.indexOf(README_END);
  if (begin === -1 || end === -1 || end < begin) throw new Error('apps/mcp/README.md is missing its tools:begin/tools:end markers');
  return readme.slice(0, begin) + region + readme.slice(end + README_END.length);
}

export async function renderToolsDoc(): Promise<string> {
  const full = (await listTools()).tools;
  const withGated = (await listTools({ deckeImprovementRead: true })).tools;
  const readOnly = (await listTools({ readOnly: true })).tools;
  const names = new Set(full.map((t) => t.name));
  const gated = withGated.filter((t) => !names.has(t.name));
  const c = await toolCounts();
  // The first sentence: a full stop followed by a capital, so "(e.g. sv03…" does not end one.
  const first = (t: AdvertisedTool) => cell(((t.description ?? '').split(/(?<=[.!?])\s+(?=[A-Z])/)[0] ?? '').trim());

  return [
    '<!-- GENERATED by `pnpm mcp:tools-doc` from the tool registry. Do not edit by hand: apps/mcp/src/__tests__/docs.test.ts fails on drift. -->',
    '',
    '# DeckPal MCP tools',
    '',
    `**${c.tools} tools: ${c.read} read, ${c.write} write**, in the order \`tools/list\` returns them, plus ${c.gated} capability-gated read tools ` +
      'shown only to a token holding the Deck-E improvement capability. A read-only connection is shown the ' +
      `${readOnly.length} read tools and none of the writes.`,
    '',
    'Every write previews by default (`dry_run` defaults to true). ' +
      '"destructive" is MCP\'s meaning: the tool may change or remove existing data, not only add to it. Most writes can be undone with ' +
      '`revert`; what can be undone, and how, is in ' +
      '`decisions/2026/2026-10-12-write-safety-battle-log-recycle-bin-deck-list-undo-retry-keys-strategy-preview.md`.',
    '',
    '| tool | title | kind | purpose |',
    '|---|---|---|---|',
    ...full.map((t) => `| [\`${t.name}\`](#${t.name}) | ${cell(t.title ?? '')} | ${hints(t)} | ${first(t)} |`),
    ...gated.map((t) => `| [\`${t.name}\`](#${t.name}) | ${cell(t.title ?? '')} | read, gated | ${first(t)} |`),
    '',
    '## Tools',
    '',
    ...full.flatMap((t) => section(t, false)),
    '## Capability-gated',
    '',
    ...gated.flatMap((t) => section(t, true)),
  ].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}
